def _attach_document_urls(request, document: dict) -> dict:
    meta = LEGAL_DOCUMENTS_BY_SLUG[document["slug"]]
    document["pdf_file_name"] = meta["file_name"]
    document["pdf_download_url"] = request.build_absolute_uri(
        reverse(
            "support-legal-document-download",
            kwargs={"slug": document["slug"]},
        )
    )
    document["detail_url"] = request.build_absolute_uri(
        reverse(
            "support-help-document",
            kwargs={"slug": document["slug"]},
        )
    )
    return document


def _document_card(request, document: dict) -> dict:
    card = {
        "id": document["id"],
        "slug": document["slug"],
        "group": document["group"],
        "label": document["label"],
        "title": document["title"],
        "summary": document["summary"],
        "description": document["description"],
        "updated_at": document["updated_at"],
        "status": document["status"],
        "revision": document["revision"],
        "operator": document["operator"],
        "approval": document["approval"],
        "sections": [],
    }
    return _attach_document_urls(request, card)


def get_help_center_content(request) -> dict:
    cards = [_document_card(request, document) for document in HELP_DOCUMENTS]
    return {
        "overview": HELP_CENTER_CONTENT["overview"],
        "document_groups": DOCUMENT_GROUPS,
        "documents": cards,
        "service_blocks": [],
        "contact_block": HELP_CENTER_CONTENT["contact_block"],
    }


def get_help_document(slug: str, request=None) -> dict | None:
    document = HELP_DOCUMENTS_BY_SLUG.get(slug)
    if document is None:
        return None

    result = deepcopy(document)
    result["pdf_file_name"] = LEGAL_DOCUMENTS_BY_SLUG[slug]["file_name"]
    if request is not None:
        _attach_document_urls(request, result)
    return result
