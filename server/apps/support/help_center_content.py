def _section(slug: str, title: str, paragraphs: list[str], bullets: list[str] | None = None) -> dict:
    return {
        "id": slug,
        "title": title,
        "paragraphs": paragraphs,
        "bullets": bullets or [],
    }


def _document(
    *,
    slug: str,
    group: str,
    label: str,
    summary: str,
    quick_facts: list[dict[str, str]],
    sections: list[dict],
    withdrawal: dict | None = None,
) -> dict:
    return {
        "id": slug,
        "slug": slug,
        "group": group,
        "label": label,
        "title": label,
        "summary": summary,
        "description": summary,
        "updated_at": REVISION_DATE,
        "status": DOCUMENT_STATUS,
        "revision": f"Редакция от {REVISION_DATE}",
        "operator": OPERATOR_NAME,
        "operator_details": OPERATOR_DETAILS,
        "approval": APPROVAL_TEMPLATE,
        "quick_facts": quick_facts,
        "table_of_contents": [
            {"id": section["id"], "title": section["title"]} for section in sections
        ],
        "sections": sections,
        "withdrawal": withdrawal,
        "archive_url": "",
    }


